      str='[demonos,timestrall,truetimes]';
      disp('List of demo numbers, expected run times, true run times:')
      table_of_run_times=[demonos,timestrall,truetimes]
      %save run times:
      %save testaod demonos timestrall truetimes rel_speed str
    end
    fdident('private','order_advice',model)
    if strncmp(version,'5',1)
      caller=getuprop(hFig,'CALLER_FCN');
    else
      caller=getappdata(hFig,'CALLER_FCN');
    end
    if strncmpi(caller,'sme',3)
      if ~isempty(findall(0,'type','figure','tag','select_main'))|...
           ~isempty(findall(0,'type','figure','tag','aided_main'))
        fdtool('callback','sme','restore_model',model,'autoorder')
      end
      %else
      %fdtool('callback','sme','sme_uic_donepb','sme_uic_donepb')
    end
