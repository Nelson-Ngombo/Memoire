      hdenom=findobj(c,'flat','tag','sme_uic_odedit');
      fdtool('callback','sme','sme_cmd_autoorderpb','sme_uic_autoorderpb','auto');  
      fdtool('callback','sme','in_axes')
      hSt= findobj(c, 'tag', 'sme_uic_startpb');
      fdtool('callback','guidtawr','aided_main','DATA_INPUT','direct',fdata);
      fdtool('callback','guidtawr','aided_main','DONE_MODELS','direct',[]);
      if get(findobj(c, 'tag', 'sme_uic_showcb'),'value')
        %I don't find the cause, only visible window allows abort'
        set(findobj(c, 'tag', 'sme_mod_abortpb'),'enable','on')
