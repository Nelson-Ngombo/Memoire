        '', ...
        '', ...
        'More topics are available, use the ''Topics'' pulldown menu.', ...
      };
    a=help('autoorder');
    helpwin({'autoorder', a;...
        'Command line option', HelpStrCommLine;...
        'Auto Model Selection Demo', char(HelpStr)});
    
  elseif isequal(varargin{1}, 'close')
    delete(hFig)
  end
