        evalin('base','autodemoresults{demoN,2}=models;')
        evalin('base','autodemoresults{demoN,3}=models;')
      end
      if strcmp(CORRTESTBASE,'nlvar')
        evalin('base','save autodemoresults2.mat autodemoresults')
      else
        evalin('base','save autodemoresults1.mat autodemoresults')
      end
    end
    while length(demonos)>length(truetimes)+1, truetimes=[truetimes;{NaN}]; end
