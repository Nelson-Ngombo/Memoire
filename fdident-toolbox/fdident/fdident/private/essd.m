  function fnnew=setfn(fntypeold,fnval,fmin,fmax);
  %Calculate fn numbers
  if strcmp(fntypeold,'# of freqs'), fnnew=fnval;
  elseif strcmp(fntypeold,'df'), fnnew=round((fmax-fmin)/(fnval+eps)+1);
  elseif strcmp(fntypeold,'df/fmin'), fnnew=round((fmax-fmin)/(fnval*fmin+eps)+1);
  elseif strcmp(fntypeold,'df/fmax'), fnnew=round((fmax-fmin)/(fnval*fmax+eps)+1);
  elseif strcmp(fntypeold,'Nf/oct'), fnnew=fnval*max(log2((fmax+eps)/(fmin+eps)),1)+1;
  elseif strcmp(fntypeold,'Nf/dec'), fnnew=fnval*max(log10((fmax+eps)/(fmin+eps)),1)+1;
  elseif strcmp(fntypeold,'df/f'), fnnew=max(log10((fmax+eps)/(fmin+eps)),1)/(fnval)+1;
  else fnnew=2;
  end
  fnnew=round(fnnew);
  
  function fnvalstr=prepfnval(fntypenew,fnnew,fmin,fmax)
  fnnew=round(fnnew);
  dfnew=(fmax-fmin)/max(fnnew-1,0.45);
  if strcmp(fntypenew,'df')
    fnvalstr=num2str(dfnew);
  elseif strcmp(fntypenew,'# of freqs')
    fnvalstr=num2str(fnnew);
  elseif strcmp(fntypenew,'df/fmin')
    fnvalstr=num2str(dfnew/max(fmin,dfnew));
  elseif strcmp(fntypenew,'df/fmax')
    fnvalstr=num2str(dfnew/fmax);
  elseif strcmp(fntypenew,'Nf/oct')
    fnvalstr=num2str((fnnew-1)/log2((fmax+eps)/(fmin+eps)));
  elseif strcmp(fntypenew,'Nf/dec')
    fnvalstr=num2str((fnnew-1)/log10((fmax+eps)/(fmin+eps)));
  elseif strcmp(fntypenew,'df/f')
    fnvalstr=num2str(log10((fmax+eps)/(fmin+eps))/(fnnew-1));
  else 
    error('Unknown popup string')
  end
  if any(findstr(fntypenew,'/'))&~isfinite(str2num(fnvalstr)), fnvalstr='1'; end
  
  function signalout=setA(signal,myfig)
  %Set the effective value here from RMS in ESSD window
  hA=[findobj(allchild(myfig),'flat','tag','essd_uic_agedit(21)');...
      findobj(allchild(myfig),'flat','tag','essd_uic_agedit_peak(21)')]; 
  Aeff=str2num(get(hA,'string'));
  hsf=findobj(allchild(myfig),'flat','tag','essd_uic_recfiltrb(1)'); %Reconstruction filter
  sfon=get(hsf,'value');
  u=signal.input; if ~iscell(u), u={u}; end
  for ii=1:prod(size(u))
    maxu=max(abs(u{ii}(:))); ueff=sqrt(mean(u{ii}(:).^2)); N=length(u{ii});
    if sfon
      interp=16; Np2=N*interp;
      if strcmp(signal.inputcharacter,'ZOH')
        indcN=ceil(signal.inputfrequencies*signal.Ts*N-0.01)+1;
        uf=u{ii}(:,ones(1,interp))'; uf=uf(:);
        UF=fft(uf); cx=UF(indcN);
        UF=zeros(1,Np2); UF(indcN)=cx;
      else %BL
        indcN=round(signal.inputfrequencies*signal.Ts*N)+1;
        if ~isempty(indcN)&any(abs(rem(indcN+0.3,1)-0.3)>1e5*eps)
          essd('status','Warning! Signal is nonperiodic')
        end
        indcN=round(indcN(:)); ind0=find(diff(indcN)==0);
        if ~isempty(ind0), indcN(ind0)=[]; end
        UFs=fft(u{ii});
        UF=zeros(1,Np2); UF(indcN)=UFs(indcN)/N*Np2; 
      end
      uf=2*real(ifft(UF)); clear UF
      maxu=max(abs(uf)); ueff=sqrt(mean(uf(:).^2));
    else
      uf=[];
    end
    signalout=signal;
    if exist('krgodfrey.mat')
      u{ii}=u{ii}/maxu*Aeff;
    else
      u{ii}=u{ii}/ueff*Aeff;
    end
    %if nargout>=2, uf=uf/ueff*Aeff; end
  end %ii
  if length(u)==1, u=u{1}; end
  set(signalout,'input',u);
  %End of setA
  
