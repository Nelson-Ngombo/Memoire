  hfmax=findobj(c, 'flat', 'tag', 'essd_uic_figrb(6)');
  fmax=str2num(get(hfmax,'string'));
  
  hfntype=findobj(c, 'flat', 'tag','essd_uic_figpopup(4)');
  fntype=popupstr(hfntype);
  prev=get(hfntype,'userdata');
  if isempty(prev), prev='df'; end
  hF=findobj(c, 'flat', 'tag', 'essd_uic_figrb(7)');
  if strcmp(prev,'# of freqs')
    F=str2num(get(hF,'string'));
  else
    fnval=str2num(get(hF,'string'));
    F=setfn(prev,fnval,fmin,fmax);
  end
  %
  if (F<1)|~isfinite(F), F=1, fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr), end
  if abs(F-round(F))<1e-5*F
    F=round(F);
    fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr)
  end
  if rem(F,1)~=0, %round to integer
    if strncmp(mode,'adjust',6)
      F=round(F); set(hF,'string',num2str(F))
    else
      errmsg='Error: noninteger number of frequencies';
      return
    end
  end
  
  h=findobj(c, 'flat', 'tag', 'essd_uic_genpop');
  tmpstr=get(h,'string');
  tmpval=get(h,'value');
  gentype=tmpstr{tmpval};
  
  h=findobj(c, 'flat', 'userdata', 'essd_uic_fgrb', 'value',1);
  freqdist_str=get(h,'string');
  
  hN=findobj(c, 'flat', 'tag', 'essd_uic_ssedit');
  N=str2num(get(hN,'string'));
  hfc=findobj(c, 'flat', 'tag', 'essd_uic_cfedit');
  fc=str2num(get(hfc,'string'));
  if strncmp(mode,'adjust',6)
    if fc<=0
      if strncmp(mode,'adjust',6)
        fc=abs(max(abs(fb),max(fc))); if fc==0, fc=1e-6; end
        set(hfc,'string',num2str(fc))
      else
        errmsg='Error: Clock frequency is non-positive';
        return
      end
    end
    if strcmp(lower(type_str), 'prbs')
      if rem(N,1)~=0, %round to integer
        N=round(N); set(hN,'string',num2str(N))
      end
    elseif any(findstr(lower(freqdist_str),'third'))&any(findstr(lower(freqdist_str),'odd'))
      if rem(N,6)~=0, %round to integer
        N=6*round(N/6); set(hN,'string',num2str(N))
      end
    elseif findstr(lower(freqdist_str),'third')
      if rem(N,3)~=0, %round to integer
        N=3*round(N/3); set(hN,'string',num2str(N))
      end
    else
      if rem(N,2)~=0, %round to even integer
        N=2*round(N/2); set(hN,'string',num2str(N))
      end
    end
    if fmax==0
      fmax=fc/N; fmin=fmax;
      set(hfmax,'string',num2str(fmax));
      set(hfmin,'string',num2str(fmin));
    end
  else %check
    if strcmp(lower(type_str), 'prbs')
      if rem(N,1)~=0, %not integer
        errmsg='Error: noninteger number of samples';
        return
      end
    elseif findstr(lower(freqdist_str),'third')&findstr(lower(freqdist_str),'odd')
      if rem(N,6)~=0, %round to integer
        errmsg='Error: number of samples is not a multiple of 6';
        return
      end
    elseif findstr(lower(freqdist_str),'third')
      if rem(N,3)~=0, %round to integer
        errmsg='Error: number of samples is not a multiple of 3';
        return
      end
    else
      if rem(N,2)~=0, %not even integer
        errmsg='Error: noninteger or odd number of samples';
        return
      end
    end
  end
  
  %if strncmp(mode,'adjust',6)
  %  if isempty(fmax), fmax=fc/2; end
  %end
  
  hfb=findobj(c, 'flat', 'tag', 'essd_uic_figrb(17)');
  fb=str2num(get(hfb,'string'));
  if ~isempty(fb)&(fb<=0)
    if strncmp(mode,'adjust',6)
      fb=abs(max(abs(fb),abs(fc))); if fb==0, fb=1e-6; end
      set(hfb,'string',num2str(fb))
    else
      errmsg='Error: Bit frequency is non-positive';
      return
    end
  end
  if (strcmp(lower(type_str),'dibs')|strcmp(lower(type_str),'dits'))&0 %fb inactive now
    if fc<fb
      %fc=fb; set(hfc,'string',num2str(fc))
      fb=fc; set(hfb,'string',num2str(fb))
    end
    Np=fc/fb;
    Npnew=round(Np);
    if abs(rem(Np+0.3,1)-0.3)>Np*eps*1e3
      if strncmp(mode,'adjust',6)
        fc=fb*Npnew; set(hfc,'string',num2str(fc))
      else
        errmsg='Error: clock frequency is not an integer multiple of the bit frequency';
        return
      end
    end
  end
  
  if findstr(lower(freqdist_str),'odd')&strcmp(lower(type_str),'prbs')
    lengthmod=2; %inverse repeat
  else
    lengthmod=1;
  end
  
  h=findobj(c, 'flat', 'userdata', 'essd_uic_agrb', 'value',1);
  ampdist_str=get(h,'string');
  
  h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(19)');
  reglength=str2num(get(h,'string'));
  if strcmp(lower(type_str), 'prbs')  % PRBS
    if strncmp(mode,'adjust',6)
      reglengthi=reglength;
      if reglength>30, reglengthi=30;
      elseif reglength<0, reglengthi=2;
      else reglengthi=round(reglength);
      end
      if reglengthi~=reglength
        reglength=reglengthi;
        set(h,'string',num2str(reglength));
      end         
    else %check
      if (reglength<1)|(reglength>30)|(rem(reglength,1)~=0)
        errmsg='Error: Register length not allowed';
        return
      end
    end
  end
  
  hA=[findobj(c, 'flat', 'tag', 'essd_uic_agedit(21)');findobj(c, 'flat', 'tag', 'essd_uic_agedit_peak(21)')];
  A=str2num(get(hA,'string'));
  
  h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(17)');
  stepfreq=str2num(get(h,'string'));
  
  hif=findobj(c, 'flat', 'tag', 'essd_uic_recfiltrb(1)'); %Smoothing filter on
  reconstruction_filter=get(hif,'enable');
  if strcmp(reconstruction_filter,'on')|strcmp(reconstruction_filter,'inactive')
    reconstruction_filter=get(hif,'value');
  else
    reconstruction_filter=0;
  end
  %reconstruction_filter=1 means that reconstruction is required
  
  %Begin checks
  if strcmp(lower(type_str), 'prbs')  % PRBS
    Nreg=2^reglength-1;
    if strncmp(mode,'adjust',6)
      stepfreq=fc/max(round(fc/stepfreq),1);
      hsf=findobj(allchild(myfig), 'flat', 'tag', 'essd_uic_figrb(17)');
      set(hsf, 'string', num2str(stepfreq))
      N=Nreg*lengthmod*round(fc/stepfreq);
      set(hN, 'string',num2str(N))
      if N>1e5, errmsg=sprintf('N=%.0f would be too large',N); return, end
    else %give warning/error
      Ni=Nreg*lengthmod*fc/stepfreq;
      if abs(N-Ni)>Ni*100*eps
        errmsg='Warning: Fractional period in PRBS';
      end
    end
  end
  %
  %Check allowed properties of generator
  if reconstruction_filter==1, rfi='on'; else rfi='off'; end
  data=fdhwcall('Properties',gentype,'fe',fc,'Ne',N,'reconstruction_filter',rfi,'A',A);
  if isstruct(data)
    if strncmp(mode,'adjust',6)
      if data.fe~=fc
        fc=data.fe; set(hfc,'string',num2str(fc))
      end
      if data.Ne~=N
        if strcmp(lower(type_str), 'prbs')  % PRBS
          errmsg='Warning: cannot generate PRBS as given';
          N=data.Ne; set(hN,'string',num2str(N))
          stepfreq=fc*N/Nreg;
          hsf=findobj(allchild(myfig), 'flat', 'tag', 'essd_uic_figrb(17)');
          set(hsf, 'string', num2str(stepfreq))
        end
      end
      if ~strcmp(data.reconstruction_filter,rfi)
        hif2=findobj(c, 'flat', 'tag', 'essd_uic_recfiltrb(2)'); %reconstruction filter off
        %reconstruction_filter=get(hif,'enable');
        %if strcmp(reconstruction_filter,'on'), reconstruction_filter=get(hif,'value'); end
        if strcmp(data.reconstruction_filter,'on')
          %Switch on
          set(hif,'value',1,'enable','on'), set(hif2,'value',0,'enable','on')
        else
          %Switch off from on
          set(hif,'value',0), set(hif2,'value',1)
        end
      end
      if data.A~=A
        A=data.A; set(hA,'string',num2str(A))
      end
    else %check
      if data.fe~=fc
        errmsg='Error: Clock frequency not allowed'; return
      end
      if data.Ne~=N
        if strcmp(lower(type_str), 'prbs')  % PRBS
          errmsg='Warning: cannot generate one sample per bit';
        else
          errmsg='Error: number of samples not allowed'; return    
        end
      end
      if ~strcmp(data.reconstruction_filter,rfi)
        errmsg='reconstruction filter setting not allowed'; return    
      end
      if data.A~=A
        errmsg='RMS value not allowed'; return    
      end
    end
  end
  
  if strcmp(lower(type_str),'multisine')|strcmp(lower(type_str),'dibs')|...
      strcmp(lower(type_str),'dits')
    %Now the number of samples will be set if necessary (adjustn)
    if strcmp(mode,'adjustn')
      switch lower(freqdist_str)
        case {'linear','odd linear','odd odd linear','randomized odd linear','special odd',...
              'no third harmonics','odd, no third harmonics','quasilog','randomized odd quasilog',...
              'all dft freqs', 'most dft freqs'}
          switch lower(freqdist_str)
            case 'linear', df=(fmax-fmin)/(F-0.999999);
            case 'odd linear', df=(fmax-fmin)/(2*(F-0.9999999));
            case 'odd odd linear', df=(fmax-fmin)/(4*(F-0.9999999));
            case 'special odd', df=(fmax-fmin)/(4*(F-0.9999999));
            case 'randomized odd linear', df=(fmax-fmin)/(3*(F-0.9999999));
            case 'no third harmonics', df=(fmax-fmin)/(3/2*(F-0.9999999));
            case 'odd, no third harmonics', df=(fmax-fmin)/(3*(F-0.9999999));
            case 'quasilog', df=(fmax-fmin)^(1/(F-0.9999999))-fmin;      
            case 'randomized odd quasilog', df=(fmax-fmin)^(1/(F-0.9999999))-fmin;      
            case 'all dft freqs', df=(fmax-fmin)/(F-0.9999999);  
            case 'most dft freqs', df=(fmax-fmin)/(F-0.9999999);  
          end
          if df>fc/2, df=fc/2; end
          if fc<=2*fmax
            fc=4*fmax; set(hfc,'string',num2str(fc))
            if strcmp(lower(type_str),'dibs')|strcmp(lower(type_str),'dits')
              fc=4*fmax; set(hfc,'string',num2str(fc))
              if abs(rem(fc/fb+0.3,1)-0.3)>fc*eps*1000
                Nov=round(fc/fb); fb=fc/Nov; set(hfb,'string',num2str(fb))
              end
            end
          end
          N=round(fc/df/2)*2; set(hN,'string',num2str(N))
        end
      end %adjustn
      %
      if N<4, N=4; set(hN,'string',num2str(N)), end
      Np=N;
      if rem(Np,1)~=0
        if strncmp(mode,'adjust',6)
          Np=round(Np); N=Np;
          set(hN,'string',num2str(N))
        else %may not adjust
          errmsg='Error: Noninteger number of periods.'
          return
        end
      end
      if fmax>fc/2
        if strncmp(mode,'adjust',6)
          fmax=fc/2*(Np/2-1)/(Np/2);
          set(hfmax,'string',num2str(fmax))
        else %may not adjust
          errmsg='Error: fmax is larger than fc/2.';
          return
        end
      end
      if fmin>fmax
        if strncmp(mode,'adjust',6)
          fmin=fmax*(Np/2-F+1)/(Np/2); if fmin<0, fmin=0; end
          set(hfmin,'string',num2str(fmin))
        else %may not adjust
          errmsg='Error: fmin is larger than fmax.';
          return
        end
      end
      % 
      dfi=fc/Np; %df in the DFT of a period
      
      %First set common values
      switch lower(freqdist_str)
        case {'linear','odd linear','odd odd linear','special odd','randomized odd linear',...
              'no third harmonics','odd, no third harmonics','quasilog','odd quasilog','randomized odd quasilog',...
              'all dft freqs', 'most dft freqs'}
          switch lower(freqdist_str)
            case 'linear', fiall=[0:Np/2]';
            case 'odd linear', fiall=[1:2:Np/2]';
            case 'odd odd linear', fiall=[1:4:Np/2]';
            case 'special odd', fiall=sort([1:8:Np/2,3:8:Np/2]');
              if strncmp(mode,'adjust',6)
                F=length(fiall); %fmin=min(fiall)*dfi; fmax=max(fiall)*dfi;
              end
            case 'randomized odd linear', fiall=sort([1:2:Np/2]');
            case 'no third harmonics', fiall=sort([1:3:Np/2,2:3:Np/2]');
            case 'odd, no third harmonics', fiall=sort([1:6:Np/2,5:6:Np/2]');
            case 'quasilog', fiall=[1:(Np+1)/2-1]';      
            case {'randomized odd quasilog','odd quasilog'}, fiall=[1:2:(Np+1)/2-1]';      
            case 'all dft freqs', fiall=[0:Np/2]';  
            case 'most dft freqs', fiall=[1:(Np+1)/2-1]';  
          end
          ind=find((fiall>fmin/dfi-0.5)&(fiall<fmax/dfi+0.5));
          fiposs=fiall(ind);
          %Randomize grid
          fmini=min(fiposs)*dfi; fmaxi=max(fiposs)*dfi;
          if strcmp(lower(freqdist_str),'randomized odd linear')
            indn=1:3:length(fiposs)-2; indn=floor(indn+3*(1-eps)*rand(size(indn)));
            fiposs(indn)=[];
          end
          if F>length(fiposs)
            if strncmp(mode,'adjust',6)
              F=length(fiposs);
              fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr)
            else %do not adjust
              errmsg='Error: number of frequencies is too large for given rule';
              return
            end
          end
          if abs(fmin-fmini)>dfi/100
            if strncmp(mode,'adjust',6)
              fmin=fmini;
              set(hfmin,'string',num2str(fmin))
            else %may not adjust
              if ~any(findstr(lower(errmsg),'error'))
                errmsg='Warning: fmin differs from the desired DFT frequency';
                fmin=fmini;
                set(hfmin,'string',num2str(fmin))
              end
            end
          end
          if abs(fmax-fmaxi)>dfi/100
            if strncmp(mode,'adjust',6)
              fmax=fmaxi;
              set(hfmax,'string',num2str(fmax))
            else %may not adjust
              if ~any(findstr(lower(errmsg),'error'))
                errmsg='Warning: fmax differs from desired DFT frequency';
                fmax=fmaxi;
                set(hfmax,'string',num2str(fmax))
              end
            end
          end
          
          switch lower(freqdist_str)  
            case {'linear','odd linear','odd odd linear','randomized odd linear',...
                  'quasilog','odd quasilog','randomized odd quasilog',...
                  'special odd','no third harmonics','odd, no third harmonics'}
              if F==1
                freqvect=(fmax+fmin)/2;
                if strncmp(mode,'adjust',6) %pull to DFT grid
                  [minv,ii]=min(abs(freqvect-fiall*dfi));
                  freqvect=fiall(ii)*dfi;
                end
                if fmax~=fmin
                  if strncmp(mode,'adjust',6)
                    fmin=freqvect; fmax=fmin; 
                    set(hfmin,'string',num2str(fmin))
                    set(hfmax,'string',num2str(fmax))
                  else 
                    if ~any(findstr(lower(errmsg),'error'))
                      errmsg='Warning:  freqs = 1, but fmin ~= fmax';
                    end
                  end
                end
              else %F>1
                switch lower(freqdist_str)
                  case 'linear'
                    %possible to deviate from grid
                    fimin=max(0,ceil(fmin/dfi-0.001));
                    fimax=min(round(Np/2),floor(fmax/dfi+0.001));
                  case 'odd linear'
                    fimin=max(1,ceil((fmin/dfi-1.001)/2)*2+1);
                    fimax=min(round(Np/2),floor((fmax/dfi+1.001)/2)*2-1);
                  case 'odd odd linear'
                    fimin=max(1,ceil((fmin/dfi-1.001)/4)*4+1);
                    fimax=min(round(Np/2),floor((fmax/dfi+3.001)/4)*4-3);
                  case {'quasilog','randomized odd quasilog'}
                    fimin=max(ceil(fmin/dfi-0.001),1);
                    fimax=min(floor(fmax/dfi+0.001),round(Np/2));
                  otherwise
                    fimin=max(ceil(fmin/dfi-0.001),1);
                    ind=min(find(fiall>=fimin)); fimin=fiall(ind);
                    fimax=min(floor(fmax/dfi+0.001),round(Np/2));
                    ind=max(find(fiall<=fimax)); fimax=fiall(ind);
                end   
                Ni=length(fiposs);              
                if Ni<F
                  if strncmp(mode,'adjust',6)
                    F=Ni;
                    fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr)
                  else
                    errmsg='Error: cannot place more than one frequency';
                    return
                  end
                elseif (F<Ni)&~any(findstr('quasilog',lower(freqdist_str)))
                  essd('status','Warning: less harmonics required than possible in the given frequency range')
                end
                if fimax==fimin
                  if strncmp(mode,'adjust',6)
                    fimax=fimax+1;
                    fmax=fimax*dfi;
                    set(hfmax,'string',num2str(fmax))
                  else
                    errmsg='Error: cannot place more than one frequency';
                    return
                  end
                end
                if strncmp(mode,'adjust',6)
                  fmin=fimin*dfi; set(hfmin,'string',num2str(fmin))
                  fmax=fimax*dfi; set(hfmax,'string',num2str(fmax))
                end
                %
                switch lower(freqdist_str)
                  case 'linear'
                    freqvect=dfi*([0:F-1]'/(F-1)*(fimax-fimin)+fimin);
                    %frequencies must be pulled to DFT grid! 
                    %if strncmp(mode,'adjust',6)
                    if freqvect(1)==0; f0=1; else f0=0; end
                    freqvect=log2qlog(freqvect,fimax,dfi); %pull to DFT grid
                    if f0&~any(freqvect==0), freqvect=[0;freqvect]; end
                    %end
                  case {'odd linear','odd odd linear'}
                    if strcmp(lower(freqdist_str),'odd linear'), ds=2; else ds=4; end
                    fmod=Ni/F;
                    freqvect=dfi*[fimin:fmod*ds:fimax]';
                    for ii=1:length(freqvect)
                      [minv,iii]=min(abs(freqvect(ii)/dfi-fiall));
                      freqvect(ii)=fiall(iii)*dfi;
                    end %for ii
                  case {'quasilog','odd quasilog','randomized odd quasilog'}       
                    Fmin=2; Fmax=fimax-fimin+1;
                    rfmin=fimax/(fimax-1); rfmax=fimax/fimin;
                    %
                    rfnew=(fimax/fimin)^(1/(F-1));
                    if any(findstr('odd',lower(freqdist_str))), di=2; else di=1; end
                    freqvect=lin2qlog(dfi*[fimin:di:fimax]',rfnew);
                    if any(findstr('randomized',lower(freqdist_str)))
                      for ii=fimin:3*di:fimax-2
                        if all(ismember(dfi*(ii+[0,di,2*di]),freqvect))
                          ind=find(dfi*ii==freqvect)+floor(3*(1-eps)*rand(1,1));
                          if ind<=length(freqvect), freqvect(ind)=[]; end
                        end
                      end
                    end
                    Fnew=length(freqvect);
                    %
                    while Fnew~=F
                      if Fnew<F, Fmin=Fnew; rfmax=rfnew;
                      elseif Fnew>F, Fmax=Fnew; rfmin=rfnew;
                      end
                      rfnew=(rfmin*rfmax^9)^(1/10);
                      freqvect=lin2qlog(dfi*[fimin:di:fimax]',rfnew);
                      if any(findstr('randomized',lower(freqdist_str)))
                        for ii=fimin:3*di:fimax-2
                          if all(ismember(dfi*(ii+[0,di,2*di]),freqvect))
                            ind=find(dfi*ii==freqvect)+floor(3*(1-eps)*rand(1,1));
                            if ind<=length(freqvect), freqvect(ind)=[]; end
                          end
                        end
                      end
                      Fnew=length(freqvect);
                    end %while
                    %end quasilog
                  case 'randomized odd linear'
                    if F>1
                      indv=round([1:F]/F*length(fiposs));
                      ind=find(diff(indv)==0); if ~isempty(indv), indv(ind)=[]; end
                    else indv=imin;
                    end
                    freqvect=fiposs(indv)*dfi;
                  otherwise
                    imin=min(find(fiall>=fimin)); 
                    imax=max(find(fiall<=fimax));
                    if F>1, indv=round(imin:(imax-imin)/(F-1):imax+0.5);
                    else indv=imin;
                    end
                    freqvect=fiall(indv)*dfi;
                  end %make freqvect in different cases
                  %
                  if F~=length(freqvect)
                    if strncmp(mode,'adjust',6)
                      F=length(freqvect);
                      fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr)
                    else
                      errmsg='Error: frequency number mismatch';
                      return
                    end
                  end
                end %F>1
              case {'all dft freqs', 'most dft freqs'}
                %set F to proper value
                if strncmp(mode,'adjust',6)
                  switch lower(freqdist_str)
                    case 'all dft freqs'
                      fmin=0; fmax=ceil(Np/2)*dfi;
                    otherwise
                      fmin=0.995*dfi; fmax=(ceil(Np/2)-0.995)*dfi;
                  end
                end
                if F~=length(fiall)
                  if strncmp(mode,'adjust',6)
                    F=length(fiall);
                    fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr)
                  else %may not adjust
                    errmsg='Error: number of freqs differs from defined number of frequencies';
                    return
                  end
                end
                freqvect=fiall*dfi;
            end  
          case 'import...'  %import 
            freqvect=guidtard(Me, 'IMPORTDATA_FREQ');
            if size(freqvect,1)==1, freqvect=freqvect.'; end
            if any(freqvect<0)
              errmsg='Error: Negative frequency in vector';
              return
              %enable View 
              h=[findobj(get(myfig,'children'), 'flat', 'tag', 'essd_uic_viewpb')];
              set(h, 'enable', 'on');
              return
            end         
          case 'matlab expression'
            freqstr=guidtard(Me, 'EXPR_DATA_FREQ');
            [status, freqvect]=CalcMatlabExpr('FREQ', freqstr, fc, dfi);
            if ~status
              %errmsg='Error in evaluating frequency vector. See command window for details.';
              %disp([lasterr ' Check Matlab expression.'])
              return   
            end
            if size(freqvect,1)==1, freqvect=freqvect.'; end
            if any(freqvect<0)
              errmsg='Error: Negative frequency in vector';
              %enable View 
              h=[findobj(get(myfig,'children'), 'flat', 'tag', 'essd_uic_viewpb')];
              set(h, 'enable', 'on');
              return
            end
            
          otherwise
            error('case ended without match')
          end %freqdist_str
          
          cond=strcmp(lower(freqdist_str),'import...')|...
            strcmp(lower(freqdist_str),'matlab expression');
          adj=cond&strcmp(get(findall(c, 'tag','essd_uic_adjustpb'),'userdata'),'adjusted');
          if strncmp(mode,'adjust',6)|adj
            %pull frequencies to DFT grid
            set(findall(c, 'tag','essd_uic_adjustpb'),'userdata','adjusted')
            freqvect=dfi*round(freqvect/dfi);
            if ~isempty(freqvect)
              freqvect=sort(freqvect);
              dfreqvect=diff(freqvect);
              if ~isempty(dfreqvect)
                ind=find(dfreqvect==0);
                if ~isempty(ind), freqvect(ind)=[]; end
                ind=find(freqvect>fc/2*(1+10*eps));
                if ~isempty(ind), freqvect(ind)=[]; end
              end
              fmax=max(freqvect); set(hfmax,'string',num2str(fmax))
            end
            F=length(freqvect);
            fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr)
            %set(hF,'userdata',freqvect) %store adjusted freqvect
          elseif ~strncmp(mode,'adjust',6)
            %check only frequencies
            if any(freqvect>fc/2*(1+10*eps))
              errmsg='Error: frequencies surpass half of clock frequency';
              %return
            end
            if any(abs(freqvect-dfi*round(freqvect/dfi))>1e-5*freqvect)
              %definitely wrong
              errmsg='Error: Frequency vector misses DFT grid. Use ''Adjust'', or correct.';
              %enable View 
              h=[findobj(get(myfig,'children'), 'flat', 'tag', 'essd_uic_viewpb')];
              set(h, 'enable', 'on');
              %return
            elseif (lengthmod==2)&any(rem(round(freqvect/dfi),2)==0)
              %definitely wrong
              errmsg='Error: Even frequency indices in vector. Use ''Adjust'', or correct.';
              %enable View 
              c=get(myfig,'children');
              h=[findobj(c, 'flat', 'tag', 'essd_uic_viewpb')];
              set(h, 'enable', 'on');
              %return
            end
          end %adjust
          dfifv=dfcalc([freqvect(:)]);
          if (dfifv>dfi)&(abs(dfifv-dfi)>1e-5)
            Np=N*dfi/dfifv;
            dfi=dfifv;
          end
          Tp=Np/fc;
          Tr=N/fc;
          
          %AMPVECT CALCULATION
          ampvect=zeros(size(freqvect)); %default
          switch lower(ampdist_str)
            case 'constant'
              ampvect=ones(size(freqvect));
            case '1/f'
              ampvect=ones(size(freqvect));
              if freqvect(1)==0
                errmsg='Cannot calculate 1/f for zero frequency point';
                return
              end
              ampvect=ampvect./freqvect;
            case 'f'
              ampvect=ones(size(freqvect));
              ampvect=ampvect.*freqvect;
            case 'follow frf' 
              if nargout>=4 %amplitude requested
                frf_data=guidtard(Me, 'IMPORTDATA_FRF');
                if isa(frf_data,'iddat')
                  fvfrf=frf_data.freqpoints;   
                  u=frf_data.input;
                  if iscell(u), u=u{1}; end
                  y=frf_data.output;
                  if iscell(y), y=y{1}; end
                else
                  fvfrf=frf_data.places;
                  u=frf_data.u; u=u(:,:,1); y=frf_data.y; y=y(:,:,1);
                end
                Ff=length(fvfrf);
                fvfrf=[-eps;fvfrf;max(2*fvfrf(Ff),max(freqvect))];
                tfrf=[abs(y(1)/u(1));abs(y./u);abs(y(Ff)/u(Ff))];
                ampvect=interp1(fvfrf,tfrf,freqvect);
              end  
            case 'optimize for model'
              if nargout>=4 %amplitude requested
                model_data=guidtard(Me, 'IMPORTDATA_MODEL');
                var_data=guidtard(Me, 'IMPORTDATA_FRF');
                fvvar=var_data.inputfreqpoints;
                u=var_data.input; u=u(:,:,1); y=var_data.output; y=y(:,:,1);
                Ff=size(fvvar,1);
                fvvar=[-eps;fvvar;max(2*fvvar(Ff),(1+eps)*max(freqvect))];
                vxy=var_data.SiSoVariance;
                tvar=[vxy(1,:);vxy;vxy(Ff,:)];
                varmod=interp1(fvvar,tvar,freqvect);
                ampvect=[];
                h=findall(0,'tag','essd_uic_cycledit');
                cycles=str2num(get(h,'string'));
                %cycles=3;
                plotdens=min(cycles,10);
                while isempty(ampvect)
                  hfo=figure(9); %Gyuszi! gyors fix, hogy ne rajzoljon a recorder-be!
                  if isnumeric(varmod), varmod=varmod/2; %prepare old call
                  else
                    for ii=1:length(varmod), varmod{ii}=varmod{ii}/2; end
                  end
                  %New call:
                  runmod.Ncyc=cycles;
                  runmod.plotdens=plotdens;
                  model_data.data=fiddata(ones(size(freqvect)),ones(size(freqvect)),freqvect);
                  model_data.data.SiSoVariance=varmod;
                  %ampvectdat=optexcit(model_data,freqvect,varmod,[],[],cycles,[],plotdens);
                  ampvectdat=optexcit(model_data,[],runmod);
                  ampvect=ampvectdat.input;
                  %ez a szabalyokkal ellentetes, de egyelore mukodik:
                  set(hfo,'tag','optexcit plot')
                  dismispb('optexcit plot')
                end
              end
            case 'import...'
              ampvect=guidtard(Me, 'IMPORTDATA_AMPL');
              if size(ampvect,1)==1, ampvect=ampvect.'; end
              ampvect=abs(ampvect);
            case 'matlab expression'
              ampstr=guidtard(Me, 'EXPR_DATA_AMPL');
              [status, ampvect]=CalcMatlabExpr('AMPL', ampstr, freqvect);
              if ~status
                errmsg=[lasterr ' Check Matlab expression.'];
                essd('status', errmsg)
                %essd('status', 'Error in evaluating amplitude vector. See command window for details.')
                %disp([lasterr ' Check Matlab expression.'])
                return   
              end
              if size(ampvect,1)==1, ampvect=ampvect.'; end
              ampvect=abs(ampvect);
            otherwise
              error('empty case statement')  
            end
            if any(size(ampvect)~=size(freqvect))
              errmsg=sprintf(['Error: Sizes of amplitude and frequency vectors do not match: ',...
                  '%.0fx%.0f ~= %.0fx%0.f'],size(freqvect,1),size(freqvect,2),size(ampvect,1),size(ampvect,2));
              if strncmp(mode,'adjust',6)
                F=length(ampvect);
                if F>0, fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr), end
              end
              %enable View 
              %h=[findobj(get(myfig,'children'), 'flat', 'tag', 'essd_uic_viewpb')];
              %set(h, 'enable', 'on');
              return
            end
            %if ~isequal(reconstruction_filter,1)
            %  sincvect=sin(pi*(freqvect+eps)/fc)./(pi*(freqvect+eps)/fc);
            %  ampvect=ampvect(:)./abs(sincvect(:));
            %end
            xt=zeros(1,1,0);
            
          elseif strcmp(lower(type_str), 'prbs')  % PRBS
            Nreg=2^reglength-1;
            Np=N;
            if rem(Np,lengthmod)~=0
              if ~any(findstr(lower(errmsg),'error'))
                errmsg='Error: Noninteger number of periods.';
              end
              return
            end
            dfi=fc/Np;
            %if reglength>30
            %   essd('status','Register length is too large')
            %   guifreez(Me, 'unfreeze', 'essd_view_spectrum');
            %   return
            %end
            xt=mlbs(reglength); 
            if lengthmod==2
              nx=length(xt)-1;
              bitmod=[ones(1,nx/2);-ones(1,nx/2)]; bitmod=[bitmod(:);1];
              xt=xt.*bitmod; xt=[xt;-xt];
            end
            plmod=1;
            if (Np~=Nreg*lengthmod)|(fc~=stepfreq)
              ind=floor([0:Np-1]'*stepfreq/fc)+1;
              ind=rem(ind-1,Nreg*lengthmod)+1;
              %maybe more periods?
              if (rem(stepfreq/fc,1)==0)&(stepfreq/fc>1)&(rem(Np/(stepfreq/fc),1)==0)
                plmod=stepfreq/fc;
                for ii=2:plmod
                  if any(ind(1:Np/plmod)~=ind((ii-1)*Np/plmod+[1:Np/plmod]))
                    plmod=1; break
                  end
                end
              end
              xt=xt(ind);
              if fc<stepfreq
                if ~any(findstr(lower(errmsg),'error'))
                  errmsg='Warning: bit series subsampled.';
                end
              elseif fc>stepfreq
                if ~any(findstr(lower(errmsg),'error'))
                  errmsg='Warning: bit series oversampled.';
                end
              elseif Np<Nreg*lengthmod
                if ~any(findstr(lower(errmsg),'error'))
                  errmsg='Warning: number of samples truncated.';
                end
              elseif Np>Nreg*lengthmod
                if ~any(findstr(lower(errmsg),'error'))
                  errmsg='Warning: number of samples extended.';
                end
              end    
            end
            dfi=fc/Np*plmod;
            cx=fft(xt(1:Np/plmod));
            if strcmp(lower(freqdist_str),'most dft freqs')
              inda=2:(length(cx)-1)/2;
              freqvect=[1:length(inda)]'*dfi;
            elseif strcmp(lower(freqdist_str),'all dft freqs')
              inda=1:(length(cx)+1)/2;
              freqvect=[0:length(inda)-1]'*dfi;
            elseif strcmp(lower(freqdist_str),'odd linear')|strncmpi(lower(freqdist_str),'Inverse repeat',14)
              inda=2:2:(length(cx)-1)/2;
              freqvect=[1:2:2*length(inda)]'*dfi;
            else
              error('incorrect string')
            end
            cx=cx(inda); ampvect=abs(cx); ampvect=ampvect/max(ampvect);
            Tr=N/fc; Tp=Np/fc/plmod;
            fmin=min(freqvect); fmax=max(freqvect); F=length(freqvect);
            if isequal(reconstruction_filter,0)&~strncmpi(gentype,'Discrete seq',12)
              sincvect=sin(pi*(freqvect+eps)/fc)./(pi*(freqvect+eps)/fc);
              ampvect=ampvect(:).*abs(sincvect(:));
              if ~isempty(cx), cx=cx(:).*abs(sincvect(:)); end
            end
          else %unknown type
            error(['Signal type ',type_str,' not known'])
          end %different signal types
          
          if any(abs(rem(freqvect*N/fc+0.3,1)-0.3)>100*eps*freqvect*N/fc)
            ermsg='Frequency vector misses DFT grid. Use ''Adjust'', or correct manually.';
          end
          %
          % fill info data
          h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(5)');
          set(h, 'string', num2str(fmin))
          h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(6)');
          set(h, 'string', num2str(fmax))
          h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(7)');
          fnvalstr=prepfnval(fntype,F,fmin,fmax); set(hF,'string',fnvalstr)
          %end
          h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(9)');
          if ~exist('plmod'), plmod=1; end
          set(h, 'string', num2str(N/Np*plmod))
          h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(11)');
          set(h, 'string', num2str(Np))
          h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(13)');
          set(h, 'string', num2str(dfi))
          h=findobj(c, 'flat', 'tag', 'essd_uic_figrb(15)');
          set(h, 'string', num2str(Tr))
          %
          parameters.fmin=fmin;
          parameters.fmax=fmax;
          parameters.fc=fc;
          parameters.stepfreq=stepfreq;
          parameters.dfi=dfi;
          parameters.F=F;
          parameters.N=N;
          parameters.periodno=N/Np;
          parameters.type_str=type_str;
          parameters.cx=cx;
          if abs(rem(Np+0.3,1)-0.3)>1e4*N*eps
            pOK=0;
            for ii=1:N/Np*(1+1e4*eps)
              if abs(rem(ii*Np+0.3,1)-0.3)<1e4*N*eps, pOK=1; iiOK=ii; break, end
            end
            ststxt=['#yPeriod length covers fractional number of samples: ',num2str(Np)];
            if pOK
              ststxt=[ststxt,sprintf('  (but %.0f periods cover exactly %.0f samples)',iiOK,round(iiOK*Np))];
            end
            essd('status',ststxt)
          end
          
