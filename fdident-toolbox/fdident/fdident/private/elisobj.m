Objects in the Frequency Domain System Identification Toolbox
=============================================================

In the fdident toolbox three classes (three object types) are defined and used.

  fiddata - frequency domain system identification data object
  fidmodel - frequency domain system identification model object
  tiddata - time domain data object for frequency domain system identification
  
Detailed information is available through the following commands:
  
Creators:
  help fiddata, help fidmodel, help tiddata
Object details:
  help(fiddata), help(fidmodel), help(tiddata)
Available functions:
  helpc(fiddata), helpc(fidmodel), helpc(tiddata)  
