%Help on Fdident GUI: Different User Levels
% 
%    Uitoggletools can set "UserLevel", and by this, modify the complexity of 
%    the GUI. At this moment "Automatic", and "Interactive" levels are 
%    available.
% 
%    At level "Automatic", a number of default settings and automatic 
%    processing steps are made. This includes automatic data preprocessing and 
%    automatic order selection (see the help of the block "Estimate Plant 
%    Model", when you already have preprocessed data at its input).
% 
%    At level "Intermediate", settings can be set manually. Moreover, at 
%    intermediate level excitation signals can be designed, and complex aspects 
%    of the models can be viewed.
% 
% 
%    Other topics are also available, use the Topics menu.