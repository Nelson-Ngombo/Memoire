%Help on Fdident GUI: Helps
% 
%    There are several levels of help on the main window and on the next level 
%    windows.
% 
%    The quickest and simplest facility is provided by pop-up helps. When the 
%    mouse is moved over an object, usually a "balloon help" pops up with the 
%    most essential information. Exceptions are "patches" (colored areas in 
%    block diagrams) and axes which do not yet have this possibility in MATLAB 
%    - for these a simple click on the object brings up a brief help in the 
%    bottom line of the window, or even better, the facility "Help on Object" 
%    can be used.
% 
%    Help can also be gotten through the Help menu, for the GUI in general, and 
%    for the current window. The menu item "Help on Object" allows getting help 
%    on most visible objects in a window, by clicking on them with the question 
%    mark.
% 
%    Many ideas and examples are available from the demonstrations, available 
%    from the "Help" menu of the main window.
% 
%    Other topics are also available, use the Topics menu.