%Help on Fdident GUI: Arrows
% 
%    Arrows can be opened in any state by double-click (or right button click), 
%    but the commands Save/Plot/Activate are only accessible if data are 
%    present.
% 
%    "Load" is a special possibility to directly bring/restore data to the GUI 
%    without activating a block. It is intelligent in the sense that it checks 
%    the data type before loading. After "Load", a special dark green color 
%    shows that data were directly loaded instead of generating them using a 
%    block.
% 
%    "Save" is the opposite pair of "Load". It stores the data of the selected 
%    arrow into a file or to the workspace.
% 
%    "Activate" means that two different arrows contain data at the input of a 
%    block (Variances and/or Averaging, or Compare and Evaluate Models), and we 
%    want to activate the "secondary" arrow. 
% 
%    Other topics are also available, use the Topics menu.