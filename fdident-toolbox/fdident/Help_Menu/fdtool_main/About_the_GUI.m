%Help on Fdident GUI: About the GUI
% 
%    The Graphical User Interface for frequency domain system identification is 
%    based on a flow graph. Blocks represent actions, and arrows represent 
%    data. A double-click or a right-button mouse click opens the desired 
%    object. This is true in general for the whole GUI: double-click on many 
%    objects will open them, or zoom-in, or bring up additional information.
% 
%    The states of the individual elements are color-coded (see Colors). Some 
%    blocks only become selectable when data appear on their input.
% 
%    When an inadequate setting is detected, the interface gracefully returns 
%    for correction with a warning or an error message. The only situation it 
%    cannot cope with occurs when during execution of an action, the mouse 
%    selects another control, which starts a parallel action. Therefore, start 
%    a new action only when the previous one is done (see the status line at 
%    the bottom of the main window).
% 
%    In most cases the user is prevented from too early actions by making the 
%    marker inactive (hourglass-form). However, parallel execution can cause 
%    such possibilities on certain platforms. When this happens, the marker may 
%    remain inactive. In such a case move the cursor a little bit over a 
%    window. This will allow again the continuation of the work. If this does 
%    not help, select "File" / "Unfreeze GUI" in the main window.
% 
%    Other topics are also available, use the Topics menu.