%Help on Getting Started...: User Levels and Signal Types
%     
%   One of the most powerful new features is the user's freedom to choose the 
%   complexity level of data processing.
%   Signal type "All" means that the user may throw arbitrary input-output 
%   data into the GUI, and fully automatic preprocessing is done to prepare 
%   the parametric model fit.
%   Signal type "Periodic" is similar, with the difference that periodic 
%   excitation is required.
%   UserLevel "Automatic" means that possibly all steps are done without 
%   bothering the user by questions. 
%   "Interactive" allows the user to influence the processing steps, while 
%   "Advanced" allows to use quite tricky settings.
%   
%   Other topics are also available, use the Topics menu.'