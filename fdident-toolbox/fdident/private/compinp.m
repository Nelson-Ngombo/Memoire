function [w_data,status,msg,err_h]=chk_w_data(w_data,win_h,isfrfdb);
%Common checks of I/O data for time and frequency
status=1; msg=''; err_h=[];
if nargin<3, isfrfdb=0; end
if isnumeric(w_data{1}), 
	if size(w_data{1},2)>1
		w_data{1}=num2cell(w_data{1},1)'; w_data{2}=num2cell(w_data{2},1)';
	else
		w_data{1}={w_data{1}}; w_data{2}={w_data{2}};
	end
end
for ii=1:length(w_data{1})
	if any(size(w_data{1}{1})~=size(w_data{1}{ii}))|...
			any(size(w_data{2}{1})~=size(w_data{2}{ii}))|...
			any(size(w_data{1}{1})~=size(w_data{2}{1}))
    ix=1:2; err_h=win_h(ix);
		if isfrfdb
			msg=['Sizes of all Gain and Phase vectors must be the same.'];
		else
			msg=['Sizes of all Input and Output vectors must be the same.'];
		end
		status=0;
		return
	end
end
if size(w_data{1}{1},2)~=1
  ix=1:2; err_h=win_h(ix);
	if isfrfdb
		msg=['All Gain and Phase data must contain column vectors.'];
	else
		msg=['All Input and Output data must contain column vectors.'];
	end
	status=0;
	return
end 
if isfrfdb
  isc=0;
  for ii=1:length(w_data{1})
    if any(imag(w_data{1}{ii})), isc=1; break, end
  end
  if isc
    ix=1; err_h=win_h(ix);
    msg=['All Gain data must be real.'];
    status=0;
    return
  end
  %
  isc=0;
  for ii=1:length(w_data{2})
    if any(imag(w_data{2}{ii})), isc=1; break, end
  end
  if isc
    ix=2; err_h=win_h(ix);
    msg=['All Phase data must be real.'];
    status=0;
    return
  end
end 

