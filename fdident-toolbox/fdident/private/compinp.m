function [var, status, msg]=ChkVar(Me,tag)
% check if edit/popup input variable is OK

if findstr(Me, 'freq')
   mode='freq';
elseif findstr(Me, 'time2')
   mode='time2';
else
   mode='time';
end
info_cell=dbase(mode, tag);
eval_type=info_cell{4};
obl_flag=info_cell{3};
class_size=info_cell{5};


myfig=findall(allchild(0), 'flat', 'tag', Me);
h=findall(allchild(myfig), 'flat', 'tag', tag);
style=get(h, 'style');
if strcmp(style, 'edit')
   str=get(h, 'string');
   str=deblank(str(end:-1:1)); str=str(end:-1:1);
   if isempty(str), isset=0; else isset=1; end
else % popupmenu
   val=get(h, 'value');
   if val==1
      isset=0;
      str='';   
   else
      isset=1;
      str=popupstr(h);
   end
end

if ~isset 
   if obl_flag
      var=[]; status=0; 
      if strcmp(style, 'edit')
         msg='Error: This field may not be empty.';
      else % popup 'Choose one';
         msg='Error: Please select an option...';
      end
   else
      var=[]; status=1;
      msg='Input OK.';
   end
   return
end

if eval_type==1 % literal
   var=str;
   status=1;
   msg='';
else
  [var, status, msg]=GetVarfromStr(str);
  myfig=[findall(0,'type','figure','tag','fdtool_compinput_time_main'),...
    findall(0,'type','figure','tag','fdtool_compinput_time2_main')];
  if ishandle(myfig)
    if strcmp(tag,'ui_fdidgui_compinp_edit_ts'),
      hts=findall(myfig,'tag',tag);
      if exist('setappdata.m'), setappdata(hts,'Ts',var)
      else setuprop(get(hts,'parent'),'Ts',var)
      end
    elseif strcmp(tag,'ui_fdidgui_compinp_edit_data_inp')|...
        strcmp(tag,'ui_fdidgui_compinp_edit_data_out')
      if ~isempty(var)
        %if iscell(var), var=var{1}; end
        myfig=[findall(0,'type','figure','tag','fdtool_compinput_time_main'),...
    findall(0,'type','figure','tag','fdtool_compinput_time2_main')];
        hts=findall(myfig,'tag','ui_fdidgui_compinp_edit_excitfreq');
        if exist('setappdata.m'), setappdata(hts,'N',length(var))
        else setuprop(get(hts,'parent'),'N',length(var))
        end
      end
    end
  end
end

if isempty(var) & obl_flag
   status=0; msg='Error: This field may not be empty.';
end
  
if status
	% check size
	if (strcmp(tag,'ui_fdidgui_compinp_edit_data_out')|...
			strcmp(tag,'ui_fdidgui_compinp_edit_data_inp')|...
			strcmp(tag,'ui_fdidgui_compinp_edit_data_ref')|...
			strcmp(tag,'ui_fdidgui_compinp_edit_data_out_gain')|...
			strcmp(tag,'ui_fdidgui_compinp_edit_data_out_phase')) & ...
			iscell(var)
		var_save=var;
		if size(var_save,1)~=1
			msg=['Error: cell array must be a cell row vector.'];
			status=0; return
		end
	else
		var_save={var};
	end
	for ii=1:length(var_save)
		var=var_save{ii};
		s=size(var); c=class(var);
		switch(class_size(1))
			case 'd'
				req_c='double';
			case 'c'
				req_c='char';
		end
		if ~isa(var, req_c)
			msg=['Error: this variable must be ', req_c '.'];
			status=0;
		else
			% check size
			if ~strcmp(class_size(2),'x')& s(1)>str2num(class_size(2))
        if exist('str')&isstr(str)
          warning(sprintf(['Size of variable ''',str,''' is %.0f x %.0f'],class_size(1),class_size(2)))
        end
        status=0;
			elseif ~strcmp(class_size(3),'x')& s(2)>str2num(class_size(3))
				status=0;
			end
			if ~status
				switch class_size(2:3)
					case 'x1'
						t='column vector';
					case '1x'
						t='row vector';
					case '11'
						t='scalar';
				end
				msg=['Error: this variable must be a ' t '.']; 
			end
		end
	end %for ii
	if iscell(var_save)
		if length(var_save)==1, var=var_save{1}; 
		elseif length(var_save)>1, var=var_save; 
		else error('programming error')
		end
	end
end
if isempty(msg); msg='Input OK.'; end

function [var, status, msg]=GetVarfromStr(str)
% get variable from the place indicated in str
% possibilities:
% matlab expression (variable, vector spec)
% <file>
% <file>:variable
% <file>:(index)
msg='';
str=deblank(str(end:-1:1)); str=str(end:-1:1);
if isempty(str)
   var=[]; status=1; msg='Empty input.';
   return
end
if findstr(str(1), '<')
   % should contain filename
   ix1=findstr(str, '<');
   ix2=findstr(str, '>');
   ix3=findstr(str, '>:');
   ix4=findstr(str, '(');
   ix5=findstr(str, ')');
   if length(ix1)~=1 | length(ix2)~=1 |...
         length(ix4)~=length(ix5) | (length(ix4)>0 & ix4(1)<ix2+1) |...
         (isempty(ix3) & length(str)>1+max([ix2 ix5]))
      var=0;
      status=0;
      msg='Error: bad file import syntax. See ''''Help on Object'''' for syntax information.';
   else % basic syntax ok
      filename=str(ix1+1:ix2-1);
      if exist(filename, 'file')~=2
         var=0; status=0; msg=['Error: bad filename ''' filename '''.'];
      else % filename OK
         try
             w=who('-file', filename);
         catch
             w=[];
         end    
         if ~isempty(ix3) % check is variable present in the file
            varname=str(ix3+2:min([ix4-1, length(str)]));
            ix=0;
            for ii=1:length(w)
               if strcmp(w{ii},varname), ix=ii; break, end
            end
            if ix 
               try
                  s=load(filename);
                  var=getfield(s,varname);
                  status=1;
               catch
                  var=0; status=0; msg=['Error: cannot load file ''' filename '''.'];   
               end
            else
               var=0; status=0; msg=['Error: bad variable name ''' varname '''.'];
            end
         else % no varname
            if length(w)>1 % file contains multiple variables
               var=0; status=0; msg=['Error: file ''' filename ''' contains multiple variables.'];   
            else
               try
                  s=load(filename);
                  if length(w)==1
                     var=getfield(s, w{1});
                     status=1;
                  else % length(w}=0;
                     var=s;
                  end
                  status=1;
               catch
                  var=0; status=0; msg=['Error: cannot load file ''' filename '''.'];   
               end
            end
         end
         % status==1 means successfully loaded variable (may be of wrong type!!!)
         
         % check type
         if ~isa(var, 'double')& ~isa(var, 'char')
            msg=['Error: this type cannot be loaded (' class(var) ').']; var=0; status=0; 
         end
         
         if status & ~isempty(ix4) % check if index is OK
            index=str(ix4(1):end);
            try
               file_data=var;
               var=eval(['file_data' index '']);
               status=1;
            catch
               var=0; status=0; msg='Error: bad index expression. See command window for details.';
               disp(lasterr)
            end
         end % index handling
      end % filename OK
   end  % basic syntax ok
else
   % matlab expression (not filename)
   try
      if isstr(str)&~any(strcmp(str,'Ts'))&...
          ( any(findstr('Ts',str))|any(findstr('fs',str))|...
          any(findstr('Tr',str))|any(findstr('df',str)) )
        myfig=[findall(0,'type','figure','tag','fdtool_compinput_time_main'),...
          findall(0,'type','figure','tag','fdtool_compinput_time2_main')];
        if ~isempty(myfig)
          mode=1;
          hts=findall(myfig,'tag','ui_fdidgui_compinp_edit_ts');
          htsN=findall(myfig,'tag','ui_fdidgui_compinp_edit_excitfreq');
          Ts=[]; N=[];
          try
            if exist('getappdata.m')
              Ts=getappdata(hts,'Ts'); N=getappdata(htsN,'N');
            else
              Ts=getuprop(get(hts,'parent'),'Ts'); N=getuprop(get(htsN,'parent'),'N');
            end
          catch
          end
          if isempty(Ts), Ts=1; end, if isempty(N), N=128; end
          fs=1/Ts; df=fs/N; Tr=N*Ts;
        else %it is certainly freq domain
          if ~any(strcmp(str,'Ts'))&...
              (any(findstr('Tr',str))|any(findstr('df',str)) )
            myfig=findall(0,'type','figure','tag','fdtool_compinput_freq_main');
            if ~isempty(myfig)
              mode=2;
              hts=findall(myfig,'tag','ui_fdidgui_compinp_edit_freqpoints');
              fv=[];
              try
                if exist('getappdata.m')
                  fv=getappdata(hts,'fv');
                else
                  fv=getuprop(get(hts,'parent'),'fv');
                end
              catch
              end
              df=dfcalc(fv); if isempty(df), df=1; end
              Tr=1/df;
              Ts=[]; N=[];
              if isempty(Ts), Ts=1; end, if isempty(N), N=128; end
              fs=1/Ts; df=fs/N; Tr=N*Ts;
            end
            var=eval(str); 
            if isnumeric(var)&size(var,1)==1, var=var'; end
            status=1;
          end
        end
      else
        var=evalin('base', str);
        status=1;
      end
   catch
     var=0;
     status=0;
     msg='Error in expression. See command window for details';
     disp(lasterr)
   end
end


