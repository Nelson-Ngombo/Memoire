case {0,1}
  set(h_delay, 'enable', 'off');
  set(h_period, 'enable', 'off');
case 2
  set(h_delay, 'enable', 'on');
  set(h_period, 'enable', 'on');
  set(h_delay(3), 'string', 'samples');
case 3
  set(h_delay, 'enable', 'off'); 
  set(h_delay(2), 'string', 'Inf');
  set(h_delay(3), 'string', 's');
  set(h_period, 'enable', 'off', 'value', 1); % 'Periodic'
