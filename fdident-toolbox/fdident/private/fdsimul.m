function setdelay(myfig)
% enable/disable delay editbox and Periodic/One-shot pulldown
% Ampl. source     Delay      Periodic           option
% ------------------------------------------------------
% None             grey        grey                 0
% Import data      grey        grey                 1
% Model (z)        active      active               2
% Model (~z)       grey(Inf)   grey(Periodic)       3
c=allchild(myfig);
h=findobj(c,'flat','userdata','fdsimul_uic_mgrb', 'value', 1);
if isempty(h)
  option=0;
else
  str=get(h, 'tag'); 
  index=str2num(str(18)); % num char in tag
  if index==5 % import data
    option=1;
  else
    moddata=guidtard(get(myfig, 'tag'), 'IMPORTDATA_MODEL');
    domain=moddata.variable;
    if any(findstr(domain, 'z'))
      option=2;
    else
      option=3;
    end
  end
end

